export const brandKey = (s: string) => s.toLowerCase().replace(/[®™]/g, '').replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '');
const INDEX = new Map<string, Brand>();
for (const b of BRANDS) for (const n of [b.name, ...(b.aliases ?? [])]) if (!INDEX.has(brandKey(n))) INDEX.set(brandKey(n), b);

/** Marke zu einem Herstellernamen aus dem Katalog (inkl. Schreibvarianten) */
export function findBrand(name?: string | null): Brand | null {
  if (!name) return null;
  const k = brandKey(name);
  return INDEX.get(k) ?? INDEX.get(k.replace(/^by/, '')) ?? null;
}
export const brandLogo = (name?: string | null) => { const b = findBrand(name); return b ? `/brands/${b.logo}` : null; };
export const brandSlug = (b: Brand) => b.name.toLowerCase().replace(/&/g, ' und ').replace(/'/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
